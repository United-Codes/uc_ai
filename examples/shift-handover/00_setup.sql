-- ---------------------------------------------------------------------------
-- Memory off, whatever state this schema was in
-- ---------------------------------------------------------------------------
-- Lesson 1 starts with a desk that has NO memory, and it starts that way for a
-- reader who has already been through the course once. p_drop_store also
-- removes the files, so nothing from a previous pass survives into a recording.
declare
  e_no_config exception;
  pragma exception_init(e_no_config, -20424);
begin
  uc_ai_memory.disable_for_agent(
    p_agent_code => 'MX_DESK'
  , p_drop_store => true
  );
  commit;
  sys.dbms_output.put_line('Memory of MX_DESK removed, with its files.');
exception
  when e_no_config then
    sys.dbms_output.put_line('MX_DESK has no memory yet, which is where lesson 1 starts.');
end;
