-- ---------------------------------------------------------------------------
-- The two read tools
-- ---------------------------------------------------------------------------
-- Neither tool has an argument. The asset comes from the run context, so a
-- conversation cannot point the desk at a different machine. "Build an Agent"
-- teaches why; this course only needs it to be true.
declare
  l_tool_id number;
begin
  l_tool_id := uc_ai_tools_api.merge_tool_from_schema(
    p_tool_code     => 'MX_GET_ASSET'
  , p_description   => 'Get the asset the technician is standing in front of: its name, '
                    || 'type, production line, install date, and every alarm that is '
                    || 'currently open on it. Takes no arguments.'
  , p_function_call => 'return mx_desk_pkg.get_asset(:ARGUMENTS);'
  , p_json_schema   => json_object_t('{
      "type": "object",
      "properties": {},
      "required": []
    }')
  , p_tags          => apex_t_varchar2('mxdesk')
  );
  sys.dbms_output.put_line('MX_GET_ASSET         id=' || l_tool_id);

  l_tool_id := uc_ai_tools_api.merge_tool_from_schema(
    p_tool_code     => 'MX_LIST_WORK_ORDERS'
  , p_description   => 'List the maintenance history of that same asset, newest first: '
                    || 'the symptom that was reported, the cause that was found, the '
                    || 'action taken, and the downtime in minutes. This is the '
                    || 'maintenance record of the machine. Takes no arguments.'
  , p_function_call => 'return mx_desk_pkg.list_work_orders(:ARGUMENTS);'
  , p_json_schema   => json_object_t('{
      "type": "object",
      "properties": {},
      "required": []
    }')
  , p_tags          => apex_t_varchar2('mxdesk')
  );
  sys.dbms_output.put_line('MX_LIST_WORK_ORDERS  id=' || l_tool_id);
  commit;
end;
