-- ---------------------------------------------------------------------------
-- Report
-- ---------------------------------------------------------------------------
declare
  l_assets  pls_integer;
  l_orders  pls_integer;
  l_alarms  pls_integer;
  l_tools   pls_integer;
  l_agent   pls_integer;
  l_handler pls_integer;
begin
  select count(*) into l_assets from mx_assets;
  select count(*) into l_orders from mx_work_orders;
  select count(*) into l_alarms from mx_alarms;

  select count(*) into l_tools
    from uc_ai_tools
   where code in ('MX_GET_ASSET', 'MX_LIST_WORK_ORDERS');

  select count(*) into l_agent
    from uc_ai_agents
   where code = 'MX_DESK' and status = 'active';

  -- A tool row does not check that its handler exists. Check it here, or the
  -- first run fails with PLS-00201 inside a place the reader cannot see.
  select count(*) into l_handler
    from user_objects
   where object_name = 'MX_DESK_PKG'
     and object_type = 'PACKAGE BODY'
     and status = 'VALID';

  sys.dbms_output.put_line('-------------------------------------------------------');
  sys.dbms_output.put_line('Assets:         ' || l_assets  || ' (expected 6)');
  sys.dbms_output.put_line('Work orders:    ' || l_orders  || ' (expected 18)');
  sys.dbms_output.put_line('Alarms:         ' || l_alarms  || ' (expected 6)');
  sys.dbms_output.put_line('Tools:          ' || l_tools   || ' (expected 2)');
  sys.dbms_output.put_line('Handler valid:  ' || l_handler || ' (expected 1)');
  sys.dbms_output.put_line('Agent active:   ' || l_agent   || ' (expected 1)');

  if l_assets = 6 and l_orders = 18 and l_alarms = 6
     and l_tools = 2 and l_handler = 1 and l_agent = 1
  then
    sys.dbms_output.put_line('Setup OK. Next: run 00_precheck.sql.');
  else
    sys.dbms_output.put_line('Setup INCOMPLETE. Read the numbers above.');
  end if;
  sys.dbms_output.put_line('-------------------------------------------------------');
end;
