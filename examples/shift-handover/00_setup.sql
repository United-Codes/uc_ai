declare
  procedure drop_if_exists(p_table in varchar2)
  as
    l_exists pls_integer;
    l_sql    varchar2(200 char);
  begin
    select count(*) into l_exists
      from user_tables
     where table_name = p_table and rownum = 1;

    if l_exists = 1 then
      l_sql := 'drop table ' || sys.dbms_assert.simple_sql_name(p_table)
            || ' cascade constraints purge';
      execute immediate l_sql;
    end if;
  end drop_if_exists;
begin
  drop_if_exists('MX_WORK_ORDERS');
  drop_if_exists('MX_ALARMS');
  drop_if_exists('MX_TECHNICIANS');
  drop_if_exists('MX_ASSETS');
end;
/

create table mx_assets (
  asset_no     varchar2(30 char)  not null
, asset_name   varchar2(100 char) not null
, asset_type   varchar2(50 char)  not null
, line_code    varchar2(20 char)  not null
, installed_on date               not null
, status       varchar2(20 char)  default on null 'RUNNING' not null
, constraint mx_assets_pk primary key (asset_no)
, constraint mx_assets_status_ck check (status in ('RUNNING', 'STOPPED', 'RETIRED'))
);

create table mx_technicians (
  user_name varchar2(64 char)  not null
, full_name varchar2(100 char) not null
, shift     varchar2(20 char)  not null
, constraint mx_technicians_pk primary key (user_name)
, constraint mx_technicians_shift_ck check (shift in ('EARLY', 'LATE', 'NIGHT'))
);

create table mx_alarms (
  alarm_id     number generated by default on null as identity
, asset_no     varchar2(30 char)  not null
, alarm_code   varchar2(30 char)  not null
, alarm_text   varchar2(400 char) not null
, severity     varchar2(20 char)  not null
, raised_at    date               not null
, alarm_status varchar2(20 char)  default on null 'OPEN' not null
, constraint mx_alarms_pk primary key (alarm_id)
, constraint mx_alarms_asset_fk foreign key (asset_no) references mx_assets(asset_no)
, constraint mx_alarms_status_ck check (alarm_status in ('OPEN', 'CLEARED'))
, constraint mx_alarms_severity_ck check (severity in ('LOW', 'MEDIUM', 'HIGH'))
);

create table mx_work_orders (
  wo_no            varchar2(30 char)  not null
, asset_no         varchar2(30 char)  not null
, opened_on        date               not null
, closed_on        date
, symptom          varchar2(200 char) not null
, cause            varchar2(200 char)
, action_taken     varchar2(400 char)
, downtime_minutes number
, constraint mx_work_orders_pk primary key (wo_no)
, constraint mx_work_orders_asset_fk foreign key (asset_no) references mx_assets(asset_no)
);

create index mx_work_orders_asset_ix on mx_work_orders (asset_no, opened_on desc);
create index mx_alarms_asset_ix on mx_alarms (asset_no, alarm_status);

