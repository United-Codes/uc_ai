-- Register it for this session only
-- ---------------------------------------------------------------------------
begin
  uc_ai_agents_api.set_execution_hook('SC_DESK_HOOK');
  sys.dbms_output.put_line('Hook SC_DESK_HOOK is registered for this session.');
end;
/

-- ---------------------------------------------------------------------------
-- Verification 1 — the veto reaches the caller
-- ---------------------------------------------------------------------------
-- The window is set to the current hour, so the write tool is refused right now.
create or replace package body sc_desk_hook
as
  -- Closed all day, so a write is always refused and you can see the veto.
  c_open_hour  constant pls_integer := 0;
  c_close_hour constant pls_integer := 0;

  procedure before_execution(
    p_agent_id    in number
  , p_agent_code  in varchar2
  , p_created_by  in varchar2
  , p_apex_app_id in number
  , p_session_id  in varchar2
  )
  as
  begin
    sys.dbms_output.put_line('[hook] run of ' || p_agent_code
      || ' by ' || p_created_by || ' starts.');
  end before_execution;

  procedure after_execution(
    p_exec_id       in number
  , p_status        in varchar2
  , p_input_tokens  in number
  , p_output_tokens in number
  )
  as
    -- @dblinter ignore(g-3330): an audit row must survive a rollback of the run it describes
    pragma autonomous_transaction;
  begin
    insert into sc_desk_audit (exec_id, status, input_tokens, output_tokens)
    values (p_exec_id, p_status, p_input_tokens, p_output_tokens);
    commit;
  end after_execution;

  procedure before_tool_call(
    p_agent_id    in number
  , p_agent_code  in varchar2
  , p_tool_code   in varchar2
  , p_created_by  in varchar2
  , p_session_id  in varchar2
  , p_apex_app_id in number
  )
  as
    l_hour pls_integer;
  begin
    l_hour := to_number(to_char(systimestamp, 'HH24'));

    if p_tool_code = 'SC_RAISE_CREDIT_NOTE'
       and (l_hour >= c_close_hour or l_hour < c_open_hour)
    then
      raise_application_error(-20990
        , 'The desk cannot raise a credit note outside office hours.');
    end if;
  end before_tool_call;
end sc_desk_hook;
/

declare
  l_result json_object_t;
begin
  l_result := uc_ai_agents_api.execute_agent(
    p_agent_code       => 'SC_DESK'
  , p_input_parameters => json_object_t(
      json_object('engineer_name' value 'Petra'
                , 'today'         value to_char(sysdate, 'YYYY-MM-DD')
                , 'question'      value 'Raise a credit note on INV-1001 for 780.'))
  , p_session_id       => uc_ai_agents_api.generate_session_id
  , p_run_context      => json_object_t('{"contract_id":"88","engineer":"petra.k"}')
  );
  sys.dbms_output.put_line('The run finished: ' || substr(l_result.get_clob('final_message'), 1, 120));
exception
  when others then
    -- @dblinter ignore(g-5040): the lesson shows the raised text itself
    -- @dblinter ignore(g-5080): the message IS the teaching point here
    sys.dbms_output.put_line('The veto stopped the run: ' || substr(sqlerrm, 1, 160));
end;
/

