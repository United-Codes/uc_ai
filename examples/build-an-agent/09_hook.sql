set feedback off
prompt
prompt Sessions of this agent, newest first:
prompt

select s.turn_count
     , s.message_count
     , s.total_input_tokens
     , s.total_output_tokens
     , s.created_by
     , s.audience
     , nvl(s.title, '(no title)') as title
     , nvl(s.feedback_rating, '-') as rating
  from uc_ai_agent_sessions s
 where s.root_agent_id = ( select a.id from uc_ai_agents a where a.code = 'SC_DESK' )
 order by s.started_at desc
 fetch first 5 rows only;

prompt
prompt What our own hook recorded:
prompt

select exec_id
     , status
     , input_tokens
     , output_tokens
  from sc_desk_audit
 order by id desc
 fetch first 5 rows only;

set feedback on
