-- ---------------------------------------------------------------------------
-- Make sure that the tables of Build an Agent exist
-- ---------------------------------------------------------------------------
declare
  l_tables pls_integer;
begin
  -- @dblinter ignore(g-8110): this counts four tables and compares the number, it is not an existence test
  select count(*)
    into l_tables
    from user_tables
   where table_name in ('SC_CUSTOMERS', 'SC_CONTRACTS', 'SC_ASSETS', 'SC_SERVICE_CALLS');

  if l_tables < 4 then
    raise_application_error(
      -20001
    , 'The sc_ tables are missing. Run 00_setup.sql of the course Build an Agent first.');
  end if;
end;
/

-- ---------------------------------------------------------------------------
-- Delete the objects of an earlier run
-- ---------------------------------------------------------------------------
declare
  -- Child table first, so no foreign key blocks a drop.
  c_tables constant sys.odcivarchar2list := sys.odcivarchar2list(
    'PARTNER_VISITS'
  , 'PARTNER_CLIENTS'
  );
  e_table_missing exception;
  pragma exception_init(e_table_missing, -942);
begin
  <<table_loop>>
  for i in 1 .. c_tables.count loop
    begin
      -- @dblinter ignore(g-6010): the name comes from the constant list above, not from user input
      execute immediate 'drop table ' || c_tables(i) || ' cascade constraints purge';
    exception
      when e_table_missing then
        -- @dblinter ignore(g-5080): an absent table is the normal case on a first run
        null;
    end;
  end loop table_loop;
end;
/

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

-- Which customer does a client of the A2A endpoint speak for? The client id is
-- the one UC AI builds from the name of an API key: 'apikey:' || client name.
create table partner_clients (
  client_id    varchar2(255 char) not null
, customer_id  number not null
, constraint partner_clients_pk primary key (client_id)
, constraint partner_clients_customer_fk foreign key (customer_id)
    references sc_customers (id)
);

-- A visit request. A person at the service company confirms it, so the status
-- of a request made through the agent is always REQUESTED.
create table partner_visits (
  id             number generated by default on null as identity
, asset_id       number not null
, requested_for  date not null
, status         varchar2(12 char) default on null 'REQUESTED' not null
, client_id      varchar2(255 char) not null
, created_at     timestamp default on null systimestamp not null
, constraint partner_visits_pk primary key (id)
, constraint partner_visits_asset_fk foreign key (asset_id)
    references sc_assets (id)
, constraint partner_visits_status_ck check (status in ('REQUESTED', 'CONFIRMED', 'CANCELED'))
);

create index partner_visits_asset_idx on partner_visits (asset_id);

-- ---------------------------------------------------------------------------
-- Seed data
-- ---------------------------------------------------------------------------
insert into partner_clients (client_id, customer_id) values ('apikey:ferrolux', 1);
insert into partner_clients (client_id, customer_id) values ('apikey:northwind', 2);

-- One request is open on the conveyor FX-CONV-07 (asset 1002). Lesson 3 asks the
-- agent for a second visit on the same asset, and the rule refuses it.
insert into partner_visits (asset_id, requested_for, status, client_id)
values (1002, trunc(sysdate) + 14, 'REQUESTED', 'apikey:ferrolux');

commit;

