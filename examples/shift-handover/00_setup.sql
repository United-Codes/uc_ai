-- ---------------------------------------------------------------------------
-- The prompt profile and the agent
-- ---------------------------------------------------------------------------
-- Both create_* calls make a DRAFT, and a call that does not name a version
-- resolves the ACTIVE one. So the change_status calls at the end are not
-- optional.
declare
  l_id      number;
  l_exists  pls_integer;
  l_profile uc_ai_prompt_profiles%rowtype;

  c_system_prompt constant varchar2(2000 char) :=
'You are the maintenance desk of the Aldenbruck bottling plant, line LINE-2.
You help the technician {technician_name}, who is standing at one machine. Today is {today}.

Read the asset and its maintenance history before you answer. Be short and
practical: a technician is reading this on a tablet next to a running line.';

  c_parameters constant varchar2(1000 char) := '{
      "type": "object",
      "properties": {
        "technician_name": { "type": "string", "description": "Name of the technician on shift" },
        "today":           { "type": "string", "description": "Todays date, as YYYY-MM-DD" },
        "question":        { "type": "string", "description": "What the technician asked" }
      },
      "required": ["technician_name", "today", "question"]
    }';

  -- 12 tool calls, not 8. Memory spends calls of its own, and this course
  -- measures how many in lesson 1.
  c_model_config constant varchar2(400 char) :=
    '{"g_enable_tools": true, "g_tool_tags": ["mxdesk"], "g_max_tool_calls": 12}';
begin
  -- rownum stops at the first hit: this asks "is there one?", not "how many?"
  select count(*) into l_exists
    from uc_ai_prompt_profiles
   where code = 'MX_DESK_PROFILE' and version = 1 and rownum = 1;

  if l_exists = 0 then
    l_id := uc_ai_prompt_profiles_api.create_prompt_profile(
      p_code                   => 'MX_DESK_PROFILE'
    , p_description            => 'The maintenance desk of line LINE-2.'
    , p_system_prompt_template => c_system_prompt
    , p_user_prompt_template   => '{question}'
    , p_provider               => uc_ai.c_provider_openai
    , p_model                  => uc_ai_openai.c_model_gpt_5_6_terra
    , p_model_config_json      => c_model_config
    , p_parameters_schema      => c_parameters
    );
    sys.dbms_output.put_line('profile MX_DESK_PROFILE created, id=' || l_id);
  else
    -- Reset it, so a reader who runs this again after lesson 3 gets lesson 1's
    -- profile back and not lesson 3's.
    l_profile := uc_ai_prompt_profiles_api.get_prompt_profile('MX_DESK_PROFILE', 1);
    l_profile.description            := 'The maintenance desk of line LINE-2.';
    l_profile.system_prompt_template := c_system_prompt;
    l_profile.user_prompt_template   := '{question}';
    l_profile.provider               := uc_ai.c_provider_openai;
    l_profile.model                  := uc_ai_openai.c_model_gpt_5_6_terra;
    l_profile.model_config_json      := c_model_config;
    l_profile.parameters_schema      := c_parameters;
    uc_ai_prompt_profiles_api.update_prompt_profile(p_profile => l_profile);
    sys.dbms_output.put_line('profile MX_DESK_PROFILE reset to its lesson 1 state.');
  end if;

  select count(*) into l_exists
    from uc_ai_agents
   where code = 'MX_DESK' and version = 1 and rownum = 1;

  if l_exists = 0 then
    l_id := uc_ai_agents_api.create_agent(
      p_code                   => 'MX_DESK'
    , p_description            => 'The maintenance desk agent.'
    , p_agent_type             => uc_ai_agents_api.c_type_profile
    , p_prompt_profile_code    => 'MX_DESK_PROFILE'
    , p_prompt_profile_version => 1
    , p_timeout_seconds        => 180
    );
    sys.dbms_output.put_line('agent MX_DESK created, id=' || l_id);
  else
    sys.dbms_output.put_line('agent MX_DESK is already there, left as it is.');
  end if;
end;
/

begin
  uc_ai_prompt_profiles_api.change_status(
    p_code => 'MX_DESK_PROFILE', p_version => 1
  , p_status => uc_ai_prompt_profiles_api.c_status_active);

  uc_ai_agents_api.change_status(
    p_code => 'MX_DESK', p_version => 1
  , p_status => uc_ai_agents_api.c_status_active);

  commit;
end;
